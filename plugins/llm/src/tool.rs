//! Typed tools for the model, in the spirit of `globibot_core::command`.
//!
//! Each tool is declared once with [`llm_tool!`]: the struct the arguments parse into and the
//! JSON definition sent to OpenRouter come from the same declaration, so they can't disagree.
//! Its logic is a hand-written [`Tool`] impl. A set of tools is declared with [`llm_tools!`],
//! which lists the definitions, parses a call by name and runs it.
//!
//! ```ignore
//! llm_tool! {
//!     #[tool(name = "search_lore", description = "Find the people whose lore mentions ...")]
//!     pub struct SearchLore {
//!         #[param(name = "query", description = "Words to look for")]
//!         query: String,
//!     }
//! }
//!
//! impl Tool for SearchLore {
//!     async fn run(self, ctx: &ToolCtx<'_>) -> ToolOutput { ... }
//! }
//!
//! llm_tools! {
//!     pub enum LlmTool {
//!         SearchLore(SearchLore),
//!     }
//! }
//! ```
//!
//! - Nothing is derived: every name the model sees is written out (fields get a
//!   `#[serde(rename)]` to their `name`).
//! - After `name`, every `key = value` pair is copied verbatim into the JSON: in `#[tool]` into
//!   the `function` object, in `#[param]` into the parameter's schema, over the generated keys
//!   (e.g. `enum = ASPECT_RATIOS`, or `items = json!(..)` to describe array items).
//! - A field's type gives its schema through [`ToolParam`]. Every non-`Option` field is
//!   required.

use globibot_core::{
    rpc::{self, FileAttachment},
    serenity::all::Message,
};
use parking_lot::Mutex;
use serde::de::DeserializeOwned;
use serde_json::{Map, Value, json};

use crate::{LlmPlugin, openrouter::ToolOutput};

/// What a tool run can use, while answering `asked`
pub struct ToolCtx<'a> {
    pub plugin: &'a LlmPlugin,
    pub rpc: &'a rpc::ProtocolClient,
    pub asked: &'a Message,
    /// The answer's attachments, e.g. generated images
    pub files: &'a Mutex<Vec<FileAttachment>>,
    /// The images shown to the model with `asked`, as data URLs. Their authors consented
    /// (`images::consent`), so tools can send them to the model provider too.
    pub shown_images: &'a [String],
}

/// Generated by [`llm_tool!`]
pub trait ToolSpec: DeserializeOwned {
    const NAME: &'static str;
    /// The definition sent to OpenRouter
    fn definition() -> Value;
}

/// A tool's logic. Errors are returned as text for the model.
pub trait Tool: ToolSpec {
    fn run(self, ctx: &ToolCtx<'_>) -> impl Future<Output = ToolOutput> + Send;
}

/// A type usable as a tool argument
pub trait ToolParam {
    const REQUIRED: bool = true;
    fn schema() -> Map<String, Value>;
}

fn schema_of(ty: &str) -> Map<String, Value> {
    Map::from_iter([("type".to_string(), json!(ty))])
}

impl ToolParam for String {
    fn schema() -> Map<String, Value> {
        schema_of("string")
    }
}

impl ToolParam for bool {
    fn schema() -> Map<String, Value> {
        schema_of("boolean")
    }
}

macro_rules! impl_integer_param {
    ($($ty:ty),*) => {$(
        impl ToolParam for $ty {
            fn schema() -> Map<String, Value> {
                schema_of("integer")
            }
        }
    )*};
}
impl_integer_param!(u8, u32, u64, usize);

impl<T: ToolParam> ToolParam for Vec<T> {
    fn schema() -> Map<String, Value> {
        let mut schema = schema_of("array");
        schema.insert("items".to_string(), Value::Object(T::schema()));
        schema
    }
}

impl<T: ToolParam> ToolParam for Option<T> {
    const REQUIRED: bool = false;
    fn schema() -> Map<String, Value> {
        T::schema()
    }
}

#[doc(hidden)]
pub mod __private {
    use super::*;

    pub use serde_json::{Map, Value};

    pub fn fields(fields: Vec<(&str, Value)>) -> Map<String, Value> {
        fields
            .into_iter()
            .map(|(key, value)| (key.to_string(), value))
            .collect()
    }

    pub fn to_json(value: impl serde::Serialize) -> Value {
        serde_json::to_value(value).expect("tool attributes serialize to JSON")
    }

    /// One parameter: its name, schema and whether it's required
    pub fn param<T: ToolParam>(
        name: &'static str,
        extra: Map<String, Value>,
    ) -> (&'static str, Value, bool) {
        let mut schema = T::schema();
        schema.extend(extra);
        (name, Value::Object(schema), T::REQUIRED)
    }

    pub fn definition(
        name: &str,
        extra: Map<String, Value>,
        params: Vec<(&str, Value, bool)>,
    ) -> Value {
        let required = params
            .iter()
            .filter(|(_, _, required)| *required)
            .map(|(name, _, _)| json!(name))
            .collect::<Vec<_>>();
        let properties = params
            .into_iter()
            .map(|(name, schema, _)| (name.to_string(), schema))
            .collect::<Map<_, _>>();
        let mut parameters = json!({ "type": "object", "properties": properties });
        if !required.is_empty() {
            parameters["required"] = Value::Array(required);
        }

        let mut function = Map::from_iter([("name".to_string(), json!(name))]);
        function.extend(extra);
        function.insert("parameters".to_string(), parameters);
        json!({ "type": "function", "function": function })
    }

    /// Models sometimes send no arguments at all for a tool without required ones
    pub fn parse<T: ToolSpec>(args: &str) -> Result<T, String> {
        let args = if args.trim().is_empty() { "{}" } else { args };
        serde_json::from_str(args)
            .map_err(|err| format!("Invalid arguments for {}: {err}", T::NAME))
    }

    pub fn check_unique(names: &[&str]) {
        for (i, name) in names.iter().enumerate() {
            assert!(!names[..i].contains(name), "two tools are named {name}");
        }
    }
}

/// Declares a tool's arguments and definition. See the [module docs](self).
macro_rules! llm_tool {
    (
        $(#[doc = $doc:literal])*
        #[tool(name = $name:literal $(, $key:ident = $value:expr)* $(,)?)]
        $vis:vis struct $Name:ident {
            $(
                $(#[doc = $field_doc:literal])*
                #[param(name = $param:literal $(, $param_key:ident = $param_value:expr)* $(,)?)]
                $field:ident : $ty:ty
            ),* $(,)?
        }
    ) => {
        $(#[doc = $doc])*
        #[derive(Debug, serde::Deserialize)]
        $vis struct $Name {
            $( $(#[doc = $field_doc])* #[serde(rename = $param)] pub $field: $ty, )*
        }

        impl $crate::tool::ToolSpec for $Name {
            const NAME: &'static str = $name;

            fn definition() -> $crate::tool::__private::Value {
                use $crate::tool::__private::{definition, fields, to_json};
                definition(
                    $name,
                    fields(vec![$( (stringify!($key), to_json($value)), )*]),
                    vec![$(
                        $crate::tool::__private::param::<$ty>(
                            $param,
                            fields(vec![$( (stringify!($param_key), to_json($param_value)), )*]),
                        ),
                    )*],
                )
            }
        }
    };
}
pub(crate) use llm_tool;

/// Groups tools: their definitions, parsing a call by name and running it. See the
/// [module docs](self).
macro_rules! llm_tools {
    ($(#[doc = $doc:literal])* $vis:vis enum $Name:ident { $( $Variant:ident($Tool:ty) ),* $(,)? }) => {
        $(#[doc = $doc])*
        #[derive(Debug)]
        $vis enum $Name {
            $( $Variant($Tool), )*
        }

        impl $Name {
            /// Every tool's definition. Panics if two tools share a name.
            pub fn definitions() -> Vec<$crate::tool::__private::Value> {
                $crate::tool::__private::check_unique(&[
                    $( <$Tool as $crate::tool::ToolSpec>::NAME, )*
                ]);
                vec![ $( <$Tool as $crate::tool::ToolSpec>::definition(), )* ]
            }

            /// The call of tool `name` with the model's JSON `args`. Errors are text for the model.
            pub fn parse(name: &str, args: &str) -> Result<Self, String> {
                $(
                    if name == <$Tool as $crate::tool::ToolSpec>::NAME {
                        return $crate::tool::__private::parse::<$Tool>(args).map(Self::$Variant);
                    }
                )*
                Err(format!("Unknown tool {name}"))
            }

            pub async fn run(self, ctx: &$crate::tool::ToolCtx<'_>) -> $crate::openrouter::ToolOutput {
                match self {
                    $( Self::$Variant(tool) => <$Tool as $crate::tool::Tool>::run(tool, ctx).await, )*
                }
            }
        }
    };
}
pub(crate) use llm_tools;
